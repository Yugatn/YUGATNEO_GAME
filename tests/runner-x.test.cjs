'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const game=require('../runner-x/engine.js');
const T=1/60;
function srun(){const s=game.newGame(42);game.start(s);return s;}
function noSpawns(s){s.nextObstacle=Infinity;s.nextPortal=Infinity;s.nextAgent=Infinity;s.obstacles=[];s.portals=[];s.agents=[];}
const ready=game.newGame();assert.equal(ready.phase,'ready');
assert.ok(ready.obstacles.length>2);assert.equal(ready.portals.length,1);
assert.equal(game.jump(ready),false,'cannot jump before starting');
assert.equal(game.start(ready),true);assert.equal(game.jump(ready),true);
assert.equal(game.jump(ready),false,'no infinite air jumping');
for(let i=0;i<70;i++)game.step(ready,T);
assert.equal(ready.elevation,0,'land after a normal jump');
const state=srun();noSpawns(state);
assert.equal(game.turn(state,'left'),true);assert.equal(state.lane,-1);
assert.equal(game.turn(state,'left'),false,'cannot leave track');
assert.equal(game.turn(state,'right'),true);assert.equal(state.lane,0);
assert.equal(game.camera(state),'chase');assert.equal(game.camera(state),'top');
assert.equal(game.pulse(state),false,'powers unavailable before portal');
const portal=srun();noSpawns(portal);portal.progress=137;portal.elevation=1.3;portal.vy=0;
portal.portals.push({s:138,lane:0,used:false});
for(let i=0;i<10;i++)game.step(portal,T);
assert.ok(portal.matrix>12,'jumping into portal activates Matrix time');
assert.equal(portal.portalCount,1);assert.ok(portal.bonus>=220);
assert.equal(game.pulse(portal),true,'blast available in Matrix');
assert.equal(game.pulse(portal),false,'blast cooldown enforced');
const ranged=srun();noSpawns(ranged);ranged.matrix=5;
ranged.agents=[{s:0,pace:5},{s:60,pace:3}];ranged.progress=30;
assert.equal(game.pulse(ranged),true);
assert.equal(ranged.agents.length,0,'pulse defends against approaching agents');
assert.equal(ranged.bonus,220,'power awards bounded original game points');
const wrong=srun();noSpawns(wrong);wrong.progress=244.4;
for(let i=0;i<5&&wrong.phase==='running';i++)game.step(wrong,T);
assert.equal(wrong.phase,'gameover');assert.equal(wrong.reason,'missed-turn');
const right=srun();noSpawns(right);right.progress=238;
assert.equal(game.turn(right,'right'),true);assert.equal(right.lane,0,'near corner, edge touch queues turn');
for(let i=0;i<60&&right.turnsMade===0;i++)game.step(right,T);
assert.equal(right.turnsMade,1);assert.equal(right.phase,'running');
assert.equal(game.positionAt(247).heading,1,'actual track rotates to east');
const low=srun();noSpawns(low);low.progress=379.6;
for(let i=0;i<4&&low.phase==='running';i++)game.step(low,T);
assert.equal(low.phase,'gameover');assert.equal(low.reason,'missed-step');
const high=srun();noSpawns(high);high.progress=379.5;high.elevation=1.7;high.vy=0;
for(let i=0;i<5&&high.tier===0;i++)game.step(high,T);
assert.equal(high.tier,1,'airborne runner can reach higher tier');
const evade=srun();noSpawns(evade);evade.obstacles=[{s:50.35,lane:0,type:'barrier',resolved:false}];evade.progress=50;
for(let i=0;i<3&&evade.phase==='running';i++)game.step(evade,T);
assert.equal(evade.phase,'gameover','grounded player hits obstacle');
const avoided=srun();noSpawns(avoided);avoided.obstacles=[{s:50.35,lane:1,type:'barrier',resolved:false}];avoided.progress=50;
for(let i=0;i<3;i++)game.step(avoided,T);
assert.equal(avoided.avoided,1);assert.equal(avoided.phase,'running');
const chased=srun();noSpawns(chased);chased.agents=[{s:-2,pace:12}];
for(let i=0;i<55&&chased.phase==='running';i++)game.step(chased,T);
assert.equal(chased.phase,'gameover');assert.equal(chased.reason,'agent');
const pausing=srun();noSpawns(pausing);assert.equal(game.pause(pausing),true);
const before=pausing.progress;assert.deepEqual(game.step(pausing,1),[]);assert.equal(pausing.progress,before);
game.start(pausing);game.step(pausing,1);assert.ok(pausing.progress-before<2,'large dt clamped');
const dir=['index.html','engine.js','render.js','app.js','sw.js','icon.svg','manifest.webmanifest'];
for(const name of dir)assert.ok(fs.existsSync(path.join(__dirname,'../runner-x',name)),name);
const html=fs.readFileSync(path.join(__dirname,'../runner-x/index.html'),'utf8');
assert.match(html,/telegram\.org\/js\/telegram-web-app\.js/);
for(const id of ['scene','left','right','jump','fire','camera','pause','start','overlay','hint'])assert.ok(html.includes('id="'+id+'"'),id);
const ids=[...html.matchAll(/\bid="([^"]+)"/g)].map(m=>m[1]);assert.equal(new Set(ids).size,ids.length);
const manifest=JSON.parse(fs.readFileSync(path.join(__dirname,'../runner-x/manifest.webmanifest'),'utf8'));
assert.equal(manifest.start_url,'./index.html');
console.log('PASS: 3D runner rules, turns, vertical tiers, portals, pulse, agents, score, pause and Telegram web shell');